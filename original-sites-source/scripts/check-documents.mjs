import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
import ts from 'typescript';
const require=createRequire(import.meta.url);
const fixture=process.argv[2];if(!fixture)throw new Error('Pass the path to a PDF fixture.');
fs.mkdirSync('.sites-runtime',{recursive:true});
const worker=pathToFileURL(path.resolve('public/pdf.worker.min.mjs')).href;
const clientSource=fs.readFileSync('lib/document-client.ts','utf8').replace("'/pdf.worker.min.mjs'",JSON.stringify(worker));
fs.writeFileSync('.sites-runtime/document-check.mjs',ts.transpileModule(clientSource,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText);
const {extractDocument}=await import(pathToFileURL(path.resolve('.sites-runtime/document-check.mjs')).href);
const file=new File([fs.readFileSync(fixture)],'wellbeing-policy.pdf',{type:'application/pdf'});
const document=await extractDocument(file,()=>{});
assert.ok(document.pages.length>=1);assert.ok(document.pages[0].text.includes('wellbeing'));assert.ok(document.pages[0].text.includes('workload'));
await assert.rejects(()=>extractDocument(new File(['not a PDF'],'bad.pdf',{type:'application/pdf'}),()=>{}),/not a valid PDF/);
await assert.rejects(()=>extractDocument(new File(['short'],'short.txt',{type:'text/plain'}),()=>{}),/Not enough readable text/);
await assert.rejects(()=>extractDocument(new File(['x'],'bad.exe'),()=>{}),/Choose a PDF/);
const module={exports:{}};vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/source.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{require,module,exports:module.exports,Set});
const {chunkDocument,verifyEvidence,extractedDocumentSchema}=module.exports;const chunks=chunkDocument(document);assert.ok(chunks.length);assert.equal(chunks[0].page,1);
verifyEvidence({sourceRef:chunks[0].id,evidence:chunks[0].text.slice(0,80)},chunks);
assert.throws(()=>verifyEvidence({sourceRef:chunks[0].id,evidence:'Phishing emails always require a manager to buy gift cards.'},chunks),/could not be verified/);
assert.throws(()=>verifyEvidence({sourceRef:'p99-c1',evidence:chunks[0].text.slice(0,80)},chunks),/could not be verified/);
assert.throws(()=>extractedDocumentSchema.parse({filename:'oversized.txt',pages:[{page:1,text:'a'.repeat(80001)}]}));
console.log('Document checks passed: unrelated-policy PDF extraction, page references, chunking, invalid/short/unsupported inputs, size bounds, and rejection of fabricated evidence. Browser interaction and live AI generation are not covered by this test.');
